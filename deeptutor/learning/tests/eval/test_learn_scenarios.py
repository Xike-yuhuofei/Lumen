"""Learner-scenario tests — the goal's five learner profiles plus the
transfer-evidence and prerequisite-progression guarantees.

Each test drives the production tool surface deterministically and asserts a
teaching-quality guarantee; several of them pin down failures that the
hardenings in this goal fixed (see the fixes list):

* quantitative-kp misconception stuck in remediation forever (fixed);
* a wrong answer (incl. a failed delayed-retention review) not demoting a
  mastered qualitative point (fixed);
* a failed Feynman check leaving no attempt/evidence in learner state (fixed);
* transfer answers not being distinguishable evidence (fixed — question_kind).
"""

