async def _plan(path_id):
    raw = await TeachingPlanTool().execute(_mastery_path_id=path_id)
    return json.loads(raw.content)


async def _quiz_and_grade(path_id, kp_id, answer, *, expected, misconception="", question_kind="recall"):
    question_type = "open" if ("；" in expected or "、" in expected) else "short"
    quiz = json.loads(
        (
            await MasteryQuizTool().execute(
                _mastery_path_id=path_id,
                knowledge_point_id=kp_id,
                question=f"关于 {kp_id} 的问题",
                expected_answer=expected,
                question_type=question_type,
                question_kind=question_kind,
            )
        ).content
    )
    return json.loads(
        (
            await MasteryGradeTool().execute(
                _mastery_path_id=path_id,
                answer=answer,
                question_id=quiz["question_id"],
                misconception=misconception,
            )
        ).content
    )


async def _assess(path_id, kp_id, passed):
    return json.loads(
        (
            await MasteryAssessTool().execute(
                _mastery_path_id=path_id,
                knowledge_point_id=kp_id,
                passed=passed,
                feedback="explanation" if passed else "incomplete",
            )
        ).content
    )


def _ids(path_id, material):
    """The kp ids generated by mastery_build for *path_id* (mirrors _parse_modules)."""
    return [
        f"{path_id}_m{m}_kp{j}"
        for m, mod in enumerate(material.modules)
        for j in range(len(mod.knowledge_points))
    ]


def _single_memory_module(path_id, *, name="面料、纤维、纱线、织物的区别"):
    return [
        {
            "name": "单一目标",
            "knowledge_points": [
                {
                    "name": name,
                    "type": "memory",
                    "description": "纤维是最小纺织单元；纱线是线状材料；织物是片状结构；面料是可用成品",
                    "source_ref": "纺织面料系统学#第01章",
                }
            ],
        }
    ]


def _kp_for(path_id, kp_id):
    """A minimal knowledge-point-like object for learner simulators."""
    from types import SimpleNamespace

    return SimpleNamespace(
        id=kp_id,
        name="目标",
        type="memory",
        answer="纤维是最小纺织单元；纱线是线状材料；织物是片状结构；面料是可用成品",
        misconceptions=[],
    )


# ── S1 · Strong learner is not over-taught ──────────────────────────────────


@pytest.mark.asyncio
async def test_strong_learner_not_over_taught(eval_env):
    record = await run_loop(ZHONGCAO, StrongLearner(), path_id="zhongcao", store_root=eval_env)
    assert record.completed, record.failures
    assert not record.failures

    # minimal attempts per kp: 1 qualitative pass, 3 quantitative successes
    attempts = record.final_state["attempts"]
    for kp_id, unit in zip(ZHONGCAO.kp_ids(), ZHONGCAO.modules[0].knowledge_points):
        expected = 3 if unit.type == "memory" else 1
        assert attempts[kp_id] == expected, f"{kp_id} over-taught: {attempts[kp_id]}"

    # no scaffold escalation for a learner who never struggles
    assert "show_example" not in [r["action"] for r in record.rounds]
    assert "practice" not in [r["action"] for r in record.rounds]
    assert "remediate_misconception" not in [r["action"] for r in record.rounds]

    # every decision carried a trace
    assert all(r["trace"].get("policies_evaluated") for r in record.rounds)


# ── S2 · Weak learner gets escalation then fade ─────────────────────────────


@pytest.mark.asyncio
async def test_weak_learner_scaffold_escalates_then_fades(eval_env):
    record = await run_loop(ZHONGCAO, WeakLearner(), path_id="zhongcao", store_root=eval_env)
    assert record.completed, record.failures

    # escalation happened: scaffolded practice (LIGHT) was reached
    actions = [r["action"] for r in record.rounds]
    assert "practice" in actions, f"weak learner never got scaffolded practice: {actions}"

    # scaffold trajectory for the struggling quantitative kp escalates
    # (full explain -> medium explain -> light practice) then fades to pure
    # assessment (none) once mastery recovers
    memory_id = ZHONGCAO.kp_ids()[4]
    rounds_for_kp = [r for r in record.rounds if r["focus"] == memory_id]
    assert rounds_for_kp, "memory kp was never taught"
    levels = [r["scaffold"] for r in rounds_for_kp]
    assert levels[-1] == "none", f"scaffold never faded for the weak learner: {levels}"
    assert "light" in levels, f"weak learner never reached LIGHT scaffold: {levels}"
    assert "medium" in levels, f"weak learner never reached MEDIUM scaffold: {levels}"
    assert record.final_state["mastery"][memory_id] >= 0.9
    assert record.final_state["qualitative_mastery"][ZHONGCAO.kp_ids()[0]] is True


# ── S3 · Misconception learner is detected, remediated, re-verified ─────────


@pytest.mark.asyncio
async def test_misconception_learner_detected_remediated_not_stuck(eval_env):
    record = await run_loop(
        ZHONGCAO, MisconceptionLearner(), path_id="zhongcao", store_root=eval_env
    )
    assert record.completed, f"loop failed to complete: {record.failures}"
    assert record.misconceptions, "misconceptions were never detected"

    # remediation actually ran
    assert "remediate_misconception" in [r["action"] for r in record.rounds]

    # every recorded misconception graduated (none stuck active/retrying)
    final_records = record.final_state["error_records"]
    assert final_records, "no error records recorded for the misconception learner"
    for rec in final_records:
        assert rec["status"] == "graduated", (
            f"misconception on {rec['kp']} stuck in {rec['status']} "
            f"(retries={rec['retry_count']})"
        )

    # the quantitative kp (真诚的三个条件, memory + registered misconception) must
    # NOT have been prematurely mastered before remediation — its final mastery
    # is real and its misconception graduated
    memory_id = ZHONGCAO.kp_ids()[4]
    assert record.final_state["mastery"][memory_id] >= 0.9


# ── S4 · Guessing learner never jumps to mastery ────────────────────────────


@pytest.mark.asyncio
async def test_guessing_learner_mastery_does_not_jump(eval_env):
    path_id = "guessing"
    from deeptutor.tools.mastery_tool import MasteryBuildTool as Build

    build = await Build().execute(
        _mastery_path_id=path_id, modules=_single_memory_module(path_id), mode="replace"
    )
    assert build.success

    learner = GuessingLearner()
    kp_id = "guessing_m0_kp0"
    expected = "纤维是最小纺织单元；纱线是线状材料；织物是片状结构；面料是可用成品"
    last = None
    for _ in range(24):  # enough alternating attempts
        outcome = learner.quiz(_kp_for(path_id, kp_id))
        last = await _quiz_and_grade(path_id, kp_id, outcome.answer, expected=expected)

    store = LearningStore()
    progress = store.load(path_id)
    from deeptutor.learning.policy import find_knowledge_point, is_mastered

    kp, _, _ = find_knowledge_point(progress, kp_id)
    assert kp is not None
    assert not is_mastered(progress, kp), "guessing learner reached mastery by luck"
    assert progress.mastery_levels[kp_id] < 0.9
    assert len([a for a in progress.quiz_attempts if a.knowledge_point_id == kp_id]) == 24
    assert last["mastered"] is False


# ── S5 · Forgetting learner: delayed retention failure demotes mastery ──────


@pytest.mark.asyncio
async def test_forgetting_learner_review_failure_demotes_qualitative_mastery(eval_env):
    path_id = "forgetting"
    # scope to the first concept kp only
    kp_id = _ids(path_id, ZHONGCAO)[0]
    build = await MasteryBuildTool().execute(
        _mastery_path_id=path_id, modules=ZHONGCAO.as_build_payload(), mode="replace"
    )
    assert build.success
    await MasteryGoalTool().execute(
        _mastery_path_id=path_id, name="single concept", scope_kp_ids=[kp_id]
    )

    # master the concept (qualitative pass)
    plan = await _plan(path_id)
    assert plan["decision"]["action"] == "explain"
    await _assess(path_id, kp_id, True)

    # its spaced-repetition review comes due; the learner has forgotten
    store = LearningStore()
    progress = store.load(path_id)
    force_reviews_due(progress)
    store.save(progress)

    plan = await _plan(path_id)
    assert plan["decision"]["action"] == "review", plan["decision"]
    assert plan["focus"]["node_id"] == kp_id

    graded = await _quiz_and_grade(
        path_id, kp_id, "忘了这个概念的内容", expected=ZHONGCAO.modules[0].knowledge_points[0].answer
    )
    assert graded["is_correct"] is False

    # retention failure must demote: the pass is revoked, state matches reality
    progress = store.load(path_id)
    assert progress.qualitative_mastery.get(kp_id) is False
    from deeptutor.learning.policy import find_knowledge_point, is_mastered

    kp, _, _ = find_knowledge_point(progress, kp_id)
    assert not is_mastered(progress, kp), "forgotten concept is still 'mastered'"

    # re-teaching + re-verification restores mastery
    plan = await _plan(path_id)
    assert plan["decision"]["action"] in ("explain", "assess", "show_example"), plan["decision"]
    await _assess(path_id, kp_id, True)
    progress = store.load(path_id)
    assert progress.qualitative_mastery.get(kp_id) is True


# ── S6 · Transfer evidence is tracked and affects mastery ───────────────────


@pytest.mark.asyncio
async def test_transfer_evidence_is_tracked_and_affects_mastery(eval_env):
    path_id = "transfer"
    from deeptutor.tools.mastery_tool import MasteryBuildTool as Build

    await Build().execute(
        _mastery_path_id=path_id, modules=_single_memory_module(path_id), mode="replace"
    )
    kp_id = "transfer_m0_kp0"
    expected = "纤维是最小纺织单元；纱线是线状材料；织物是片状结构；面料是可用成品"

    # three unaided recall successes → mastered
    for _ in range(3):
        await _quiz_and_grade(path_id, kp_id, expected, expected=expected)
    store = LearningStore()
    progress = store.load(path_id)
    from deeptutor.learning.policy import find_knowledge_point, is_mastered

    kp, _, _ = find_knowledge_point(progress, kp_id)
    assert is_mastered(progress, kp)
    assert progress.mastery_levels[kp_id] >= 0.9

    # a transfer question answered wrongly must weigh against mastery
    graded = await _quiz_and_grade(
        path_id, kp_id, "迁移情境答错", expected=expected, question_kind="transfer"
    )
    assert graded["is_correct"] is False
    progress = store.load(path_id)
    assert not is_mastered(progress, kp), "failed transfer did not demote mastery"
    assert progress.mastery_levels[kp_id] < 0.9

    # the transfer attempt is recorded as distinct evidence
    kinds = [
        a.question_kind
        for a in progress.quiz_attempts
        if a.knowledge_point_id == kp_id and a.question_id != f"feynman:{kp_id}"
    ]
    assert kinds[-1] == "transfer", f"transfer kind not recorded: {kinds}"

    # recovery on the transfer question restores mastery (the failed transfer
    # must age out of the recency window — stability has to be re-proven)
    for _ in range(5):
        await _quiz_and_grade(path_id, kp_id, expected, expected=expected, question_kind="transfer")
    progress = store.load(path_id)
    assert is_mastered(progress, kp)


# ── S7 · A failed Feynman check enters learner state (no invisible failures) ─


@pytest.mark.asyncio
async def test_failed_qualitative_check_updates_state_and_escalates(eval_env):
    path_id = "feynman_fail"
    kp_id = _ids(path_id, ZHONGCAO)[0]
    await MasteryBuildTool().execute(
        _mastery_path_id=path_id, modules=ZHONGCAO.as_build_payload(), mode="replace"
    )
    await MasteryGoalTool().execute(
        _mastery_path_id=path_id, name="concept only", scope_kp_ids=[kp_id]
    )

    plan = await _plan(path_id)
    assert plan["decision"]["action"] == "explain"
    # first explanation is incomplete → fail
    await _assess(path_id, kp_id, False)

    store = LearningStore()
    progress = store.load(path_id)
    # the failure must be visible: an attempt was recorded, and mastery capped
    assert len([a for a in progress.quiz_attempts if a.knowledge_point_id == kp_id]) == 1
    assert progress.mastery_levels[kp_id] <= 0.4

    # the engine now escalates instead of re-explaining from scratch
    plan = await _plan(path_id)
    assert plan["decision"]["action"] in ("show_example", "practice", "explain"), plan["decision"]
    assert plan["decision"]["action"] != "explain" or plan["decision"]["scaffold_level"] != "full"


# ── S8 · prerequisite progression (module chain) is enforced by the engine ──


@pytest.mark.asyncio
async def test_prerequisite_progression_respects_module_order(eval_env):
    textile = BENCHMARK_SET["textile"]
    path_id = "textile"
    record = await run_loop(textile, StrongLearner(), path_id=path_id, store_root=eval_env)
    assert record.completed, record.failures

    # each kp's first appearance in the plan must follow module/kp order
    order_index = {kp_id: i for i, kp_id in enumerate(_ids(path_id, textile))}
    seen: list[int] = []
    for r in record.rounds:
        focus = owning_kp_id(r["focus"])
        if focus in order_index:
            seen.append(order_index[focus])
    first_seen: list[int] = []
    for idx in seen:
        if idx not in first_seen:
            first_seen.append(idx)
    assert first_seen == sorted(first_seen), f"out-of-order teaching: {first_seen}"

    # the engine never reported COMPLETE before every target was mastered
    assert record.final_state["complete"] is True


# ── S9 · every round's decision is traceable (determinism seam) ─────────────


@pytest.mark.asyncio
async def test_decisions_are_traceable_and_deterministic(eval_env):
    # the same (material, learner) on fresh paths yields the same action
    # sequence (normalised: focus ids are path-scoped)
    def norm(record):
        return [
            (r["action"], r["focus"].replace("zhongcao_run1_", "").replace("zhongcao_run2_", ""))
            for r in record.rounds
        ]

    r1 = await run_loop(ZHONGCAO, StrongLearner(), path_id="zhongcao_run1", store_root=eval_env)
    r2 = await run_loop(ZHONGCAO, StrongLearner(), path_id="zhongcao_run2", store_root=eval_env)
    assert norm(r1) == norm(r2), "non-deterministic teaching path"
    assert all(r["trace"].get("policy_applied") for r in r1.rounds)


# ── S10 · long-struggle learner does not bloat error records ────────────────


@pytest.mark.asyncio
async def test_struggling_learner_error_records_stay_bounded(eval_env):
    """Regression: error records are keyed per knowledge point, not per
    question — a learner who answers wrong many times on one point (every
    wrong answer is a fresh question in the tool flow) must not accumulate
    an unbounded error-record list."""
    path_id = "bloat"
    await MasteryBuildTool().execute(
        _mastery_path_id=path_id, modules=_single_memory_module(path_id), mode="replace"
    )
    kp_id = "bloat_m0_kp0"
    expected = "纤维是最小纺织单元；纱线是线状材料；织物是片状结构；面料是可用成品"

    learner = GuessingLearner()
    for _ in range(30):
        outcome = learner.quiz(_kp_for(path_id, kp_id))
        await _quiz_and_grade(path_id, kp_id, outcome.answer, expected=expected)

    store = LearningStore()
    progress = store.load(path_id)
    kp_records = [
        rec for rec in progress.error_records if rec.knowledge_point_id == kp_id
    ]
    assert len(kp_records) <= 1, f"error records grew without bound: {len(kp_records)}"
    assert len(progress.quiz_attempts) == 30
