"""Phase-4b runner — bounded real-LLM teaching-content trial.

Drives :func:`phase4_realllm.run_realllm_trial` (CodexManager / gpt-5.6-terra,
preferred) and writes ``phase4_realllm_evidence.json`` +
``phase4_realllm_report.md`` into ``--out``.

Requires ``CODEXMANAGER_API_KEY`` in the environment (keys come only from env,
never from files or code). Usage:

    source ~/.zshrc
    .venv/bin/python -m tests.modes.learn.eval.bakeoff.run_phase4_realllm [--budget N] [--material zhongcao] [--learner weak] [--out DIR]
"""

from __future__ import annotations

import argparse
import contextlib
import json
from pathlib import Path
import sys


def _ensure_tests_resolvable() -> None:
    root = Path(__file__).resolve().parents[3]
    if str(root) not in sys.path:
        sys.path.insert(0, str(root))
    for entry in list(sys.path):
        p = Path(entry) / "tests"
        if p.is_dir() and (p / "__init__.py").exists():
            with contextlib.suppress(ValueError):
                sys.path.remove(entry)


def _fmt_md(r: dict) -> str:
    rows = ["# Teaching Architecture Experiment — Phase-4b Real-LLM Content Trial", ""]
    rows.append("## Scope")
    rows.append(
        f"Candidate A (untouched) vs Candidate B with REAL teaching content injected "
        f"through its content-delegation seam (prioritized CodexManager / gpt-5.6-terra), "
        f"on {r.get('material')}/{r.get('learner')}, under a hard call budget "
        f"({r.get('call_budget')})."
    )
    rows.append("")
    rows.append("## A vs B — designated outcome variables")
    rows.append("")
    rows.append("| var | A | B (real content) |")
    rows.append("|---|---|---|")
    for key, label in (
        ("completed", "completed"),
        ("mastered", "mastered (of total)"),
        ("steps", "time-to-mastery (steps)"),
        ("unprompted_success", "independent success"),
        ("retention", "retention probe"),
        ("transfer", "transfer probe"),
        ("capability_gain_per_step", "learning efficiency"),
    ):
        a, b = r["a"][key], r["b"][key]
        a_s = "true" if a is True else ("false" if a is False else (f"{a:.3f}" if isinstance(a, float) else str(a)))
        b_s = "true" if b is True else ("false" if b is False else (f"{b:.3f}" if isinstance(b, float) else str(b)))
        rows.append(f"| {label} | {a_s} | {b_s} |")
    rows.append("")
    rows.append(
        f"- outcome_equal={r.get('outcome_equal')}; real LLM calls used="
        f"{r.get('real_calls_made')}/{r.get('call_budget')}; approx max tokens="
        f"{r.get('approx_tokens_requested')}; budget_exhausted={r.get('budget_exhausted')}."
    )
    rows.append("")
    rows.append("## Real LLM content sample (first generated passages)")
    rows.append("")
    for s in (r.get("content_samples") or [])[:5]:
        if "error" in s:
            rows.append(f"- (error) {s['error']}")
        else:
            rows.append(f"- action={s.get('action')} focus={s.get('focus')} real_call={s.get('used_real_call')}")
            rows.append(f"  - {s.get('content_preview','')}")
    rows.append("")
    rows.append("## Verdict")
    rows.append(f"**{r.get('verdict')}** — {r.get('reason')}")
    rows.append("")
    rows.append("_Generated by `run_phase4_realllm.py`; raw evidence in `phase4_realllm_evidence.json`._")
    return "\n".join(rows)


async def main(budget: int, material: str, learner: str, out_dir: Path) -> int:
    _ensure_tests_resolvable()
    from .phase4_realllm import decide_realllm, run_realllm_trial

    result = await run_realllm_trial(
        budget=budget, material_id=material, learner_name=learner
    )
    verdict, reason = decide_realllm(result)
    result["verdict"] = verdict
    result["reason"] = reason

    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "phase4_realllm_evidence.json").write_text(
        json.dumps(result, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    (out_dir / "phase4_realllm_report.md").write_text(
        _fmt_md(result), encoding="utf-8"
    )
    print(f"[phase4b] verdict={verdict}")
    print(f"[phase4b] real_calls={result.get('real_calls_made')}/{budget}; outcome_equal={result.get('outcome_equal')}")
    print(f"[phase4b] evidence -> {out_dir / 'phase4_realllm_evidence.json'}")
    print(f"[phase4b] report   -> {out_dir / 'phase4_realllm_report.md'}")
    return 0


def _argparser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description="Teaching Architecture Experiment — Phase-4b real-LLM")
    p.add_argument("--budget", type=int, default=12)
    p.add_argument("--material", default="zhongcao")
    p.add_argument("--learner", default="weak")
    p.add_argument("--out", type=Path, default=Path(__file__).resolve().parent / "out_phase4_realllm")
    return p


if __name__ == "__main__":
    import asyncio

    args = _argparser().parse_args()
    sys.exit(asyncio.run(main(args.budget, args.material, args.learner, args.out)))